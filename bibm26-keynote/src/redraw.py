        s.append(f'<rect x="0" y="{y}" width="1150" height="56" rx="3" fill="{ACCT if last else GROUP}"/>')
        s.append(T(16, y + 36, a, 23))
        s.append(T(260, y + 36, b, 23, INK if last else INK2))
        s.append(T(640, y + 36, c, 23, INK if last else INK2))
